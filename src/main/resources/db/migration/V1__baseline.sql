-- =============================================================================
-- V1 — Schema inicial da Sorveteria-API
-- =============================================================================
--
-- COMO O FLYWAY LÊ ESTE ARQUIVO
--
-- O nome segue o padrão V<versão>__<descrição>.sql, e não é decorativo:
--   V1        -> a ordem em que os arquivos são aplicados (V1, depois V2, ...)
--   __        -> exatamente dois underscores separam a versão da descrição
--
-- O Flyway cria sozinho uma tabela chamada flyway_schema_history, onde anota
-- cada arquivo que já rodou e o checksum dele. Consequências práticas:
--
--   1. Migração já aplicada não roda de novo.
--   2. Se você editar um arquivo que já rodou, o checksum muda e o Flyway
--      reclama. Isso é uma proteção: schema aplicado é histórico, não se
--      reescreve. Mudança nova = arquivo novo (V2__..., V3__...).
--
-- Este V1 é o "baseline": o retrato do schema que antes era criado pelo
-- Hibernate com ddl-auto=update.
--
-- -----------------------------------------------------------------------------
-- COMO ESTE SQL FOI DERIVADO DAS ENTIDADES JAVA
-- -----------------------------------------------------------------------------
--
-- Regra de conversão automática do Hibernate (CamelCaseToUnderscoresNamingStrategy):
--   senhaHash  -> senha_hash        custoTotal -> custo_total
--   ItemPedido -> item_pedido       ultimoLogin -> ultimo_login
--
-- Regra de tipo:
--   Long      -> bigint        (chave primária com @GeneratedValue IDENTITY)
--   String    -> varchar(255)  (255 é o padrão quando não se declara length)
--   BigDecimal-> numeric(p,s)  (precisão e escala vêm de @Column)
--   int       -> integer       (tipo primitivo não aceita nulo)
--   boolean   -> boolean
--   LocalDate -> date
--   LocalDateTime -> timestamp(6)
--   enum com @Enumerated(STRING) -> varchar(255)
--
-- Detalhe que vale entender: onde o campo Java é primitivo (boolean, int) a
-- coluna fica NOT NULL, porque primitivo não aceita nulo em Java. Onde é
-- String ou BigDecimal (que aceitam nulo), a coluna também aceita — a menos
-- que a entidade declare @Column(nullable = false).
--
-- =============================================================================


-- -----------------------------------------------------------------------------
-- users — clientes da sorveteria
-- -----------------------------------------------------------------------------
-- Entidade: User.java (@Table(name = "users"))
--
-- Os campos rua/numero/cidade/estado/cep vêm de Endereco, que é uma classe
-- anotada com @Embedded na entidade e @Embeddable nela mesma. O JPA "achata"
-- esse objeto dentro da tabela do dono: não existe tabela endereco, e sim
-- essas cinco colunas dentro de users. É o padrão para dados que só fazem
-- sentido junto com o dono.
--
CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            varchar(255),
    -- @Column(unique = true, nullable = false) na entidade
    email           varchar(255) NOT NULL,
    senha_hash      varchar(255) NOT NULL,
    rua             varchar(255),
    numero          varchar(255),
    cidade          varchar(255),
    estado          varchar(255),
    cep             varchar(255),
    telefone        varchar(255),
    cpf             varchar(255),
    data_nascimento date,
    -- Campo primitivo com valor inicial true: cliente nasce ativo
    ativo           boolean NOT NULL,
    ultimo_login    timestamp(6),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- O e-mail é único. O UserService também checa antes de salvar, mas a
-- constraint aqui é a garantia de verdade: duas requisições simultâneas podem
-- passar pela checagem do Java ao mesmo tempo e gravar duplicado. Só o banco
-- consegue impedir isso de forma confiável.
--
-- O CPF não tem constraint equivalente, e o service também verifica duplicidade
-- no Java. Fica o mesmo risco de corrida. Vale considerar um UNIQUE aqui também.


-- -----------------------------------------------------------------------------
-- produto — catálogo
-- -----------------------------------------------------------------------------
-- Entidade: Produto.java (sem @Table, então o nome vem do nome da classe)
--
CREATE TABLE produto (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      varchar(255) NOT NULL,
    descricao varchar(255) NOT NULL,
    -- @Column(precision = 10, scale = 2) -> 10 dígitos no total, 2 decimais.
    -- Em dinheiro use numeric, nunca float: float não representa 0.10
    -- exatamente e o erro se acumula nas somas.
    preco     numeric(10, 2) NOT NULL,
    estoque   integer NOT NULL,
    ativo     boolean NOT NULL,
    -- @Enumerated(EnumType.STRING) grava o nome do enum como texto
    -- ("SORVETE", "ACAI"). O alternativo, EnumType.ORDINAL, gravaria a posição
    -- numérica — e aí reordenar o enum quebraria todos os dados já gravados.
    categoria varchar(255)
);


-- -----------------------------------------------------------------------------
-- sabor — sabores de sorvete
-- -----------------------------------------------------------------------------
-- Entidade: Sabor.java
--
CREATE TABLE sabor (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  varchar(255),
    ativo boolean NOT NULL
);


-- -----------------------------------------------------------------------------
-- pedido — pedidos
-- -----------------------------------------------------------------------------
-- Entidade: Pedido.java
--
-- user_id é a coluna que materializa o @ManyToOne da entidade: muitos pedidos
-- apontam para um usuário. Do lado do User existe o @OneToMany(mappedBy="user"),
-- que é apenas o espelho dessa relação — por isso não gera coluna nenhuma.
-- O lado que manda é o que tem a chave estrangeira.
--
CREATE TABLE pedido (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        varchar(255),
    -- Sem precisão declarada na entidade: o Hibernate assume numeric(38,2)
    custo_total numeric(38, 2),
    -- @Enumerated(EnumType.STRING): PENDENTE, EM_PREPARO, PRONTO, ENTREGUE, CANCELADO
    status      varchar(255),
    itens_total integer NOT NULL,
    user_id     bigint,
    CONSTRAINT fk_pedido_user FOREIGN KEY (user_id) REFERENCES users (id)
);


-- -----------------------------------------------------------------------------
-- item_pedido — itens de cada pedido
-- -----------------------------------------------------------------------------
-- Entidade: ItemPedido.java
--
-- É a tabela que resolve a relação muitos-para-muitos entre pedido e produto:
-- cada linha diz "neste pedido, deste produto, tantas unidades, a este preço".
--
-- Repare que preco_unitario é gravado no item, e não lido do produto na hora
-- de calcular. É decisão importante: se o preço do produto mudar amanhã, o
-- pedido de ontem precisa continuar valendo o que valia quando foi fechado.
-- Guardar o preço no item é o que preserva isso.
--
CREATE TABLE item_pedido (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id      bigint,
    produto_id     bigint,
    quantidade     integer NOT NULL,
    preco_unitario numeric(38, 2),
    CONSTRAINT fk_item_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT fk_item_produto FOREIGN KEY (produto_id) REFERENCES produto (id)
);


-- -----------------------------------------------------------------------------
-- Índices das chaves estrangeiras
-- -----------------------------------------------------------------------------
-- O PostgreSQL cria índice automático para chave primária e para UNIQUE, mas
-- NÃO para chave estrangeira. Sem estes índices, cada busca por "itens deste
-- pedido" varreria a tabela inteira.
--
CREATE INDEX idx_pedido_user_id ON pedido (user_id);
CREATE INDEX idx_item_pedido_pedido_id ON item_pedido (pedido_id);
CREATE INDEX idx_item_pedido_produto_id ON item_pedido (produto_id);
